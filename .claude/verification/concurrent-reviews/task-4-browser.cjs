const assert = require('node:assert/strict');
const {readFileSync, mkdirSync, writeFileSync} = require('node:fs');
const {join} = require('node:path');
const {chromium} = require('playwright');
const base = 'http://127.0.0.1:8054';
const dir = __dirname;
const screens = join(dir, 'task-4-screens');
mkdirSync(screens, {recursive:true});
(async () => {
  const browser = await chromium.launch({headless:true, args:['--no-sandbox']});
  const results = [];
  try {
    const context = await browser.newContext({viewport:{width:1280,height:900}});
    await context.addCookies([JSON.parse(readFileSync(join(dir, 'task-4-browser-data/browser-cookie.json')))]);
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(`${base}/settings/`);
    const field = page.getByLabel('Concurrent PR reviews', {exact:true});
    assert.equal(await field.inputValue(), '2');
    assert.equal(await field.getAttribute('min'), '1');
    assert.equal(await field.getAttribute('max'), '8');
    assert.equal(await field.getAttribute('step'), '1');
    await field.focus();
    await page.keyboard.press('Tab');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await field.evaluate(el=>document.activeElement===el), true);
    assert.equal(await field.evaluate(el=>getComputedStyle(el).outlineStyle), 'solid');
    assert.ok(await field.evaluate(el=>el.getBoundingClientRect().height)>=44);
    assert.match(await field.evaluate(el=>getComputedStyle(el).transitionDuration), /0.16s/);
    await page.screenshot({path:join(screens,'desktop-focus.png'),fullPage:true});
    const advanced = page.locator('.repository-options');
    assert.equal(await advanced.getAttribute('open'), null);
    await advanced.locator('summary').focus();
    await page.keyboard.press('Enter');
    assert.equal(await advanced.getAttribute('open'), '');
    await advanced.locator('summary').press('Enter');
    const stale = await context.newPage();
    await stale.goto(`${base}/settings/`);
    await field.fill('3');
    await Promise.all([page.waitForURL(`${base}/settings/`), page.getByRole('button',{name:'Save settings',exact:true}).click()]);
    await page.getByRole('status').filter({hasText:'Settings saved'}).waitFor();
    assert.equal(await field.inputValue(), '3');
    await page.screenshot({path:join(screens,'desktop-success.png'),fullPage:true});
    await stale.getByLabel('Concurrent PR reviews',{exact:true}).fill('1');
    const staleResponse = stale.waitForResponse(r=>r.url()===`${base}/settings/`&&r.request().method()==='POST');
    await stale.getByRole('button',{name:'Save settings',exact:true}).click();
    assert.equal((await staleResponse).status(),409);
    assert.match(await stale.getByRole('alert').innerText(), /another tab/);
    await stale.screenshot({path:join(screens,'desktop-stale.png'),fullPage:true});
    await stale.close();
    await field.fill('9');
    assert.equal(await field.evaluate(el=>el.validity.rangeOverflow),true);
    const invalidResponse = page.waitForResponse(r=>r.url()===`${base}/settings/`&&r.request().method()==='POST');
    await page.locator('.policy-form').evaluate(form=>{form.noValidate=true;form.requestSubmit();});
    assert.equal((await invalidResponse).status(),400);
    assert.equal(await field.getAttribute('aria-invalid'),'true');
    assert.equal(await field.inputValue(),'9');
    assert.match(await page.locator('#capacity-error').innerText(),/whole number/);
    await page.screenshot({path:join(screens,'desktop-invalid.png'),fullPage:true});
    await page.goto(`${base}/settings/`);
    assert.equal(await field.inputValue(),'3');
    for (const viewport of [{width:1280,height:900},{width:390,height:844}]) {
      await page.setViewportSize(viewport);
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
      await page.screenshot({path:join(screens,viewport.width===390?'mobile.png':'desktop.png'),fullPage:true});
      results.push({viewport,overflow:false});
    }
    await field.focus();
    await page.keyboard.press('ArrowUp');
    assert.equal(await field.inputValue(),'4');
    await page.getByRole('button',{name:'Save settings',exact:true}).click();
    await page.getByRole('status').filter({hasText:'Settings saved'}).waitFor();
    assert.equal(await field.inputValue(),'4');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:join(screens,'mobile-success.png'),fullPage:true});
    results.push({mobileKeyboardIncrement:true,mobileSaved:4});
    await page.emulateMedia({reducedMotion:'reduce'});
    await field.focus();
    assert.equal(await field.evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
    await page.screenshot({path:join(screens,'mobile-reduced-motion.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    results.push({keyboardFocus:true,controlMin44:true,saved:3,invalid400:true,stale409:true,advancedDisclosure:true,reducedMotion:true,pageErrors:errors});
    writeFileSync(join(screens,'results.json'),JSON.stringify(results,null,2));
    console.log(JSON.stringify(results));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
